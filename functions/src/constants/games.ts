type GameName = (typeof GAMES)[number]['name'];
type GameKey = (typeof GAMES)[number]['key'];

type GameCodesMap = {
  [K in GameName]: Extract<(typeof GAMES)[number], { name: K }>['code'];
};

type GameKeysMap = {
  [K in GameKey]: K;
};

type GameNamesMap = {
  [K in GameKey]: Extract<(typeof GAMES)[number], { key: K }>['name'];
};

const generateGameCodes = (): GameCodesMap =>
  GAMES.reduce((acc, entry) => {
    (acc as AnyOrUnknownPlaceholder)[entry.name] = entry.code;
    return acc;
  }, {} as GameCodesMap);

const generateGameKeys = (): GameKeysMap =>
  GAMES.reduce((acc, entry) => {
    (acc as AnyOrUnknownPlaceholder)[entry.key] = entry.key;
    return acc;
  }, {} as GameKeysMap);

const generateGameCollections = (): GameNamesMap =>
  GAMES.reduce((acc, entry) => {
    (acc as AnyOrUnknownPlaceholder)[entry.key] = entry.name;
    return acc;
  }, {} as GameNamesMap);

/**
 * Dictionary mapping game names to their single-letter codes
 */
export const GAME_CODES = generateGameCodes();

/**
 * Dictionary of game keys
 */
export const GAME_KEYS = generateGameKeys();

/**
 * Dictionary mapping game keys to game collection names
 */
export const GAME_NAMES = generateGameCollections();
